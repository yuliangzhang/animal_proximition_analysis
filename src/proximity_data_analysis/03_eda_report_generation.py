def plot_mating_rule_screening(pair_metrics: pd.DataFrame, params: Dict[str, float]) -> str:
    """Plot screening space of candidate metrics and thresholds."""
    x = pair_metrics.copy()
    cls = np.where(
        x["candidate_selected"],
        "selected",
        np.where(x["candidate_pre_cap"], "candidate_not_selected", "non_candidate"),
    )
    x["cls"] = cls

    # Downsample dense background for readability.
    non_cand = x[x["cls"] == "non_candidate"]
    if len(non_cand) > 2500:
        non_cand = non_cand.sample(2500, random_state=42)
    cand = x[x["cls"] != "non_candidate"]
    plot_df = pd.concat([non_cand, cand], ignore_index=True)

    fig, ax = plt.subplots(figsize=(10, 6))
    for c in ["non_candidate", "candidate_not_selected", "selected"]:
        g = plot_df[plot_df["cls"] == c]
        if g.empty:
            continue
        ax.scatter(
            g["count_z"],
            g["count_fc"],
            s=24 if c != "non_candidate" else 12,
            alpha=0.8 if c != "non_candidate" else 0.35,
            color=CLASS_COLORS[c],
            label=c,
            edgecolors="none",
        )

    ax.axvline(params["MATING_SCORE_THRESHOLD"], color="#f58518", linestyle="--", linewidth=1.8, label="score threshold")
    ax.axhline(params["MATING_FC_THRESHOLD"], color="#54a24b", linestyle="--", linewidth=1.8, label="fold-change threshold")

    ax.set_title("Day-level Screening Space: count_z vs count_fc")
    ax.set_xlabel("count_z")
    ax.set_ylabel("count_fc")
    ax.legend(loc="upper left", bbox_to_anchor=(1.01, 1.0), borderaxespad=0.0, frameon=True)

    fig.tight_layout()
    out = FIG_DIR / "04_mating_rule_screening.png"
    save_figure(fig, out)
    plt.close(fig)
    return out.name


def plot_ram_distribution(ram_day: pd.DataFrame) -> str:
    """Plot ram daily partner distribution with visible mean markers."""
    fig, axes = plt.subplots(1, 2, figsize=(16, 5), constrained_layout=True)

    sns.boxplot(
        data=ram_day,
        x="treatment",
        y="mating_ewe_count",
        hue="year",
        palette=YEAR_COLORS,
        width=0.62,
        showfliers=False,
        ax=axes[0],
    )
    axes[0].set_title("Ram daily mating-partner count distribution")
    axes[0].set_xlabel("Treatment")
    axes[0].set_ylabel("Ewe partners per ram-day")
    axes[0].legend(title="Year", loc="upper left", bbox_to_anchor=(1.01, 1.0), borderaxespad=0.0, frameon=True)

    stats = (
        ram_day.groupby(["year", "treatment"], as_index=False)["mating_ewe_count"]
        .agg(["mean", "std", "count"])
        .reset_index()
    )
    stats = stats.rename(columns={"mean": "mean_count", "std": "std_count", "count": "n"})
    stats["sem"] = stats["std_count"] / np.sqrt(stats["n"].clip(lower=1))

    for year in YEARS:
        g = stats[stats["year"] == year].set_index("treatment").reindex(TREATMENT_ORDER).reset_index()
        axes[1].errorbar(
            g["treatment"],
            g["mean_count"],
            yerr=g["sem"],
            marker="o",
            markersize=7,
            linewidth=2.2,
            capsize=4,
            color=YEAR_COLORS[year],
            label=str(year),
        )

    axes[1].set_title("Ram partner mean ± SEM (clear year contrast)")
    axes[1].set_xlabel("Treatment")
    axes[1].set_ylabel("Mean ewe partners per ram-day")
    axes[1].legend(title="Year", loc="upper left", bbox_to_anchor=(1.01, 1.0), borderaxespad=0.0, frameon=True)

    out = FIG_DIR / "05_ram_daily_partner_distribution.png"
    save_figure(fig, out)
    plt.close(fig)
    return out.name


