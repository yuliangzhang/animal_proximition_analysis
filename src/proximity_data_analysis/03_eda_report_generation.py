def save_figure(fig: plt.Figure, out_path: Path) -> None:
    """Save figure with extra padding to avoid clipping legends/annotations."""
    fig.savefig(out_path, bbox_inches="tight", pad_inches=0.25)


def ensure_dirs() -> None:
    """Create report folders if missing."""
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    REPORT_DIR.mkdir(parents=True, exist_ok=True)


def require_tables() -> Dict[str, pd.DataFrame]:
    """Load required CSV tables generated by analysis pipeline."""
    required = {
        "parameters": "analysis_parameters.csv",
        "prefilter_audit": "pair_prefilter_audit.csv",
        "prefilter_summary": "prefilter_summary.csv",
        "pair_metrics": "pair_signal_metrics.csv",
        "pair_event_summary": "pair_event_summary.csv",
        "anomaly": "plot_day_anomaly_metrics.csv",
        "split_index": "final_result_file_index.csv",
        "final_results": "mating_results_all.csv",
        "ram_day": "ram_day.csv",
        "ewe_summary": "ewe_summary.csv",
        "tz_summary": "tz_summary.csv",
    }

    loaded: Dict[str, pd.DataFrame] = {}
    for key, name in required.items():
        p = TABLE_DIR / name
        if not p.exists():
            raise FileNotFoundError(f"Missing required table: {p}")
        loaded[key] = pd.read_csv(p)

    return loaded


def param_map(df: pd.DataFrame) -> Dict[str, float]:
    """Convert parameter table to a key-value mapping."""
    out: Dict[str, float] = {}
    for _, row in df.iterrows():
        out[str(row["parameter"])] = float(row["value"])
    return out


def fmt_pct(numerator: float, denominator: float) -> str:
    """Format percentage with one decimal place."""
    if denominator == 0:
        return "0.0%"
    return f"{100.0 * numerator / denominator:.1f}%"


def fmt_num(value: float) -> str:
    """Format numeric parameter without unintended integer rounding."""
    if float(value).is_integer():
        return str(int(value))
    return f"{value:.3f}".rstrip("0").rstrip(".")


def df_to_markdown(df: pd.DataFrame, max_rows: int = 20) -> str:
    """Render table to markdown with fallback if tabulate is unavailable."""
    show = df.head(max_rows).copy()
    try:
        return show.to_markdown(index=False)
    except Exception:
        return "```\n" + show.to_string(index=False) + "\n```"


def preprocess_tables(tables: Dict[str, pd.DataFrame]) -> None:
    """Apply common datatype normalization for plotting and reporting."""
    tables["anomaly"]["date"] = pd.to_datetime(tables["anomaly"]["date"])
    tables["anomaly"]["management_anomaly"] = tables["anomaly"]["management_anomaly"].astype(bool)

    tables["final_results"]["is_mating"] = tables["final_results"]["Mating"].eq("Y")
    tables["final_results"]["date"] = pd.to_datetime(tables["final_results"]["date"], errors="coerce")

    if "year" in tables["ram_day"].columns:
        tables["ram_day"]["year"] = tables["ram_day"]["year"].astype(int)
    if "year" in tables["ewe_summary"].columns:
        tables["ewe_summary"]["year"] = tables["ewe_summary"]["year"].astype(int)
    if "year" in tables["tz_summary"].columns:
        tables["tz_summary"]["year"] = tables["tz_summary"]["year"].astype(int)


