def anomaly_day_summary(anomaly: pd.DataFrame) -> pd.DataFrame:
    """Return only flagged anomaly days for report tables."""
    cols = ["year", "treatment", "date", "day_total", "sync_prop", "rz_total", "rz_sync"]
    out = anomaly[anomaly["management_anomaly"]][cols].copy()
    out["date"] = out["date"].dt.date.astype(str)
    out = out.sort_values(["year", "treatment", "date"]).reset_index(drop=True)
    return out


def top_ram_insights(final_results: pd.DataFrame) -> pd.DataFrame:
    """Build top-ram insight table."""
    y = final_results[final_results["is_mating"]].copy()
    y["date_str"] = y["date"].dt.date.astype(str)
    ram = (
        y.groupby(["year", "treatment", "Ram_EID"], as_index=False)
        .agg(
            mating_events=("Mating", "count"),
            active_days=("date_str", "nunique"),
            unique_ewes=("Ewe_EID", "nunique"),
            mean_day_count=("day_proximity_times", "mean"),
        )
        .sort_values(["year", "mating_events", "active_days"], ascending=[True, False, False])
    )
    return ram


def build_time_zone_peak_table(tz_summary: pd.DataFrame) -> pd.DataFrame:
    """For each year-treatment group, find top time-zone and share."""
    rows: List[dict] = []
    for (year, treatment), g in tz_summary.groupby(["year", "treatment"]):
        total = g["mating_events"].sum()
        top = g.sort_values("mating_events", ascending=False).iloc[0]
        rows.append(
            {
                "year": int(year),
                "treatment": treatment,
                "top_time_zone": top["time_zone"],
                "top_events": int(top["mating_events"]),
                "top_share": float(top["mating_events"] / total) if total > 0 else 0.0,
            }
        )
    return pd.DataFrame(rows).sort_values(["year", "treatment"]).reset_index(drop=True)


def write_cn_report(
    tables: Dict[str, pd.DataFrame],
    params: Dict[str, float],
    fig_names: Dict[str, str],
) -> None:
    """Write Chinese report with embedded evidence and interpretations."""
    prefilter_audit = tables["prefilter_audit"]
    pair_metrics = tables["pair_metrics"]
    pair_event_summary = tables["pair_event_summary"]
    anomaly = tables["anomaly"]
    split_index = tables["split_index"]
    final_results = tables["final_results"]
    ewe_summary = tables["ewe_summary"]
    tz_summary = tables["tz_summary"]

    total_pairs_raw = int(len(prefilter_audit))
    removed_step2 = int((~prefilter_audit["pass_step2_non_zero_days"]).sum())
    removed_step4 = int((prefilter_audit["pass_step2_non_zero_days"] & (~prefilter_audit["pass_step4_robust_z"])).sum())
    kept_pairs = int(prefilter_audit["pair_prefilter_keep"].sum())

    evaluated_pair_days = int(len(pair_metrics))
    candidates_pre_cap = int(pair_metrics["candidate_pre_cap"].sum())
    selected_events = int(pair_metrics["candidate_selected"].sum())
    removed_by_cap = int(pair_metrics["candidate_removed_by_cap"].sum())
    pairs_with_candidate_days = int((pair_event_summary["candidate_days_pre_cap"] > 0).sum())
    pairs_with_selected_days = int((pair_event_summary["candidate_days_selected"] > 0).sum())
    selected_days_per_selected_pair = (
        float(selected_events) / float(pairs_with_selected_days) if pairs_with_selected_days > 0 else 0.0
    )

    flagged = anomaly_day_summary(anomaly)
    flagged_day_count = int(anomaly["management_anomaly"].sum())
    peak_tz = build_time_zone_peak_table(tz_summary)

    ram_rank = top_ram_insights(final_results)
    ram_top10 = ram_rank.head(10)

    ewe_over3 = int((ewe_summary["mating_count"] > 3).sum())
    ewe_total = int(len(ewe_summary))
