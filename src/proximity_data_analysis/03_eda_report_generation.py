def _ordered_time_zones(zones: List[str]) -> List[str]:
    """Sort time-zone strings by start hour."""
    def key(z: str) -> int:
        try:
            return int(str(z).split(":")[0])
        except Exception:
            return 99

    return sorted(set(zones), key=key)


def plot_time_zone_preference(tz_summary: pd.DataFrame) -> str:
    """Plot time-zone preference with external legend."""
    zone_order = _ordered_time_zones(tz_summary["time_zone"].dropna().tolist())
    palette = sns.color_palette("Set2", n_colors=max(3, len(zone_order)))
    zone_colors = {z: palette[i] for i, z in enumerate(zone_order)}

    fig, axes = plt.subplots(1, 2, figsize=(19, 7), sharey=True)
    fig.subplots_adjust(top=0.84, bottom=0.20, left=0.06, right=0.985, wspace=0.02)
    for idx, year in enumerate(YEARS):
        sub = tz_summary[tz_summary["year"] == year]
        pivot = (
            sub.pivot(index="treatment", columns="time_zone", values="mating_events")
            .reindex(index=TREATMENT_ORDER, columns=zone_order)
            .fillna(0)
        )

        bottom = np.zeros(len(pivot))
        for zone in zone_order:
            vals = pivot[zone].to_numpy()
            axes[idx].bar(
                pivot.index,
                vals,
                bottom=bottom,
                color=zone_colors[zone],
                label=zone,
                edgecolor="white",
            )
            bottom += vals

        axes[idx].set_title(f"{year} time-zone preference by treatment", pad=10)
        axes[idx].set_xlabel("Treatment")
        if idx == 0:
            axes[idx].set_ylabel("Mating events")

    handles = [plt.Rectangle((0, 0), 1, 1, color=zone_colors[z]) for z in zone_order]
    fig.legend(
        handles,
        zone_order,
        loc="upper center",
        ncol=min(6, len(zone_order)),
        bbox_to_anchor=(0.5, 0.985),
        frameon=True,
    )

    out = FIG_DIR / "07_time_zone_preference.png"
    save_figure(fig, out)
    plt.close(fig)
    return out.name


