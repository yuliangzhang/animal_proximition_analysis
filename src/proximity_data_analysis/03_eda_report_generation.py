def plot_prefilter_evidence(prefilter_audit: pd.DataFrame, prefilter_summary: pd.DataFrame, params: Dict[str, float]) -> str:
    """Plot evidence for pair-level pre-filter behavior."""
    fig, axes = plt.subplots(1, 2, figsize=(16, 5), constrained_layout=True)

    # Left: non-zero day distribution.
    non_zero_days = prefilter_audit["non_zero_days"].fillna(0)
    axes[0].hist(non_zero_days, bins=range(0, int(non_zero_days.max()) + 2), color="#4c78a8", alpha=0.85)
    axes[0].axvline(params["PAIR_MIN_NONZERO_DAYS"], color="#f58518", linestyle="--", linewidth=2, label="Step2 threshold")
    axes[0].set_title("Pair Non-zero Day Distribution")
    axes[0].set_xlabel("Non-zero days in full experiment window")
    axes[0].set_ylabel("Pair count")
    axes[0].legend(loc="upper right", frameon=True)

    # Right: pre-filter outcome by group.
    summary = prefilter_summary.copy()
    summary["year_treat"] = summary["year"].astype(str) + "-" + summary["treatment"]
    x = np.arange(len(summary))

    removed_step2 = summary["removed_step2_nonzero_lt7"].to_numpy()
    removed_step4 = summary["removed_step4_robust_z"].to_numpy()
    kept = summary["kept_pairs"].to_numpy()

    axes[1].bar(x, removed_step2, color="#e45756", label="Removed by Step2 (<7 days)")
    axes[1].bar(x, removed_step4, bottom=removed_step2, color="#f58518", label="Removed by Step4 (|rz|>3)")
    axes[1].bar(x, kept, bottom=removed_step2 + removed_step4, color="#54a24b", label="Kept")
    axes[1].set_xticks(x)
    axes[1].set_xticklabels(summary["year_treat"], rotation=30, ha="right")
    axes[1].set_ylabel("Pair count")
    axes[1].set_title("Pre-filter Flow by Year-Treatment")
    axes[1].legend(loc="upper left", bbox_to_anchor=(1.02, 1.0), borderaxespad=0.0, frameon=True)

    out = FIG_DIR / "01_prefilter_evidence.png"
    save_figure(fig, out)
    plt.close(fig)
    return out.name


def _plot_year_anomaly_panel(anomaly: pd.DataFrame, year: int) -> str:
    """Plot robust-z anomaly panel for one year."""
    sub = anomaly[anomaly["year"] == year].copy()
    fig, axes = plt.subplots(2, 3, figsize=(22, 9), sharex=False)
    fig.subplots_adjust(top=0.88, bottom=0.14, left=0.055, right=0.84, wspace=0.22, hspace=0.24)

    for col_idx, treatment in enumerate(TREATMENT_ORDER):
        g = sub[sub["treatment"] == treatment].sort_values("date")
        if g.empty:
            axes[0, col_idx].set_axis_off()
            axes[1, col_idx].set_axis_off()
            continue

        x = g["date"]
        flags = g["management_anomaly"]

        axes[0, col_idx].plot(x, g["rz_total"], color="#1f77b4", marker="o", linewidth=1.8, label="rz_total")
        axes[0, col_idx].scatter(x[flags], g.loc[flags, "rz_total"], color="#d62728", s=45, label="Flagged day")
        axes[0, col_idx].axhline(3.0, color="#f58518", linestyle="--", linewidth=1.4, label="Threshold +3")
        axes[0, col_idx].set_title(f"{treatment} | rz_total", pad=10)
        axes[0, col_idx].set_ylabel("Robust z-score")
        axes[0, col_idx].tick_params(axis="x", labelbottom=False)

        axes[1, col_idx].plot(x, g["rz_sync"], color="#2ca02c", marker="s", linewidth=1.8, label="rz_sync")
        axes[1, col_idx].scatter(x[flags], g.loc[flags, "rz_sync"], color="#d62728", s=45, label="Flagged day")
        axes[1, col_idx].axhline(3.0, color="#f58518", linestyle="--", linewidth=1.4, label="Threshold +3")
        axes[1, col_idx].set_title(f"{treatment} | rz_sync", pad=10)
        axes[1, col_idx].set_ylabel("Robust z-score")
        axes[1, col_idx].set_xlabel("Date")

        for ax in [axes[0, col_idx], axes[1, col_idx]]:
            ax.xaxis.set_major_locator(mdates.DayLocator(interval=2))
            ax.xaxis.set_major_formatter(mdates.DateFormatter("%Y-%m-%d"))
            ax.margins(x=0.03)
        axes[1, col_idx].tick_params(axis="x", rotation=28)

    legend_handles = [
        Line2D([0], [0], color="#1f77b4", marker="o", linewidth=1.8, label="rz_total"),
        Line2D([0], [0], color="#2ca02c", marker="s", linewidth=1.8, label="rz_sync"),
        Line2D([0], [0], color="#d62728", marker="o", linestyle="None", markersize=7, label="Flagged day"),
        Line2D([0], [0], color="#f58518", linestyle="--", linewidth=1.6, label="Threshold +3"),
    ]
    fig.legend(
        handles=legend_handles,
        loc="center left",
        ncol=1,
        bbox_to_anchor=(0.855, 0.5),
        frameon=True,
    )

    out = FIG_DIR / f"02_management_anomaly_rz_{year}.png"
    save_figure(fig, out)
    plt.close(fig)
    return out.name


